#include <iostream>
#include <cstdlib>  // Для функций rand() и srand()
#include <ctime>    // Для функции time()
#include <iomanip>  // Для форматированного вывода

using namespace std;

int main() {
    setlocale(LC_ALL, "Russian");

    int n;

    // 1. Ввод размера массивов
    cout << "ЗАДАНИЕ 2.1: Поэлементный выбор максимума" << endl;
    cout << "__________________________________________" << endl;
    cout << "Введите размер массивов (n): ";
    cin >> n;

    if (n <= 0) {
        cout << "Ошибка: размер должен быть положительным!" << endl;
        return 1;
    }

    // 2. Объявление массивов
    int* a = new int[n];
    int* b = new int[n];
    int* c = new int[n];

    // 3. Инициализация генератора случайных чисел
    srand(time(0)); // Инициализация начальным значением

    // 4. Заполнение массивов a и b случайными числами (от -50 до 50)
    cout << "\nГенерация случайных чисел в диапазоне [-50, 50]..." << endl;
    for (int i = 0; i < n; i++) {
        a[i] = rand() % 101 - 50;  // Числа от -50 до 50
        b[i] = rand() % 101 - 50;
    }

    // 5. Формирование массива c как поэлементного максимума
    for (int i = 0; i < n; i++) {
        if (a[i] > b[i]) {
            c[i] = a[i];
        }
        else {
            c[i] = b[i];
        }
    }

    // 6. Вывод результатов
    cout << "\nРезультаты:" << endl;
    cout << "Индекс | Массив A | Массив B | Максимум (C)" << endl;
    cout << "-------|----------|----------|-------------" << endl;

    for (int i = 0; i < n; i++) {
        cout << setw(6) << i << " | ";
        cout << setw(8) << a[i] << " | ";
        cout << setw(8) << b[i] << " | ";
        cout << setw(12) << c[i] << endl;
    }

    // 7. Освобождение памяти
    delete[] a;
    delete[] b;
    delete[] c;

    return 0;
}